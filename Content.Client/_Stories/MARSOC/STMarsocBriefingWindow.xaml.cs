    private void UpdatePortraitTexture(string path)
    {
        if (!string.IsNullOrWhiteSpace(path) &&
            _resourceCache.TryGetResource<TextureResource>(path, out var requestedRes))
        {
            _loadedPortraitPath = path;
            PortraitTextureRect.Texture = requestedRes.Texture;
            return;
        }

        foreach (var candidate in CandidatePortraitPaths)
        {
            if (_resourceCache.TryGetResource<TextureResource>(candidate, out var candidateRes))
            {
                _loadedPortraitPath = candidate;
                PortraitTextureRect.Texture = candidateRes.Texture;
                return;
            }
        }
    }

    public void UpdateState(STMarsocBriefingBuiState state)
    {
        OperationTitleLabel.Text = state.OperationTitle;
        SpeakerNameLabel.Text = state.SpeakerFullNameAndRank;
        IntelSummaryLabel.Text = state.DetectedIntelSummary;
        DropSectorLabel.Text = Loc.GetString(DropSectorDisplayLoc, ("sector", state.SelectedSectorName));

        if (_loadedPortraitPath != state.PortraitTexturePath)
            UpdatePortraitTexture(state.PortraitTexturePath);

        var segmentsChanged = _segments.Count != state.DialogueSegments.Count;
        if (!segmentsChanged)
        {
            for (var i = 0; i < _segments.Count; i++)
            {
                if (_segments[i] != state.DialogueSegments[i])
                {
                    segmentsChanged = true;
                    break;
                }
            }
        }

        if (segmentsChanged)
        {
            _segments.Clear();
            _segments.AddRange(state.DialogueSegments);
            StartSegment(0);
        }

        ObjectivesListContainer.RemoveAllChildren();
        for (var i = 0; i < state.Objectives.Count; i++)
        {
            var escapedObjective = FormattedMessage.EscapeText(state.Objectives[i]);
            var itemLabel = new RichTextLabel
            {
                HorizontalExpand = true,
                Margin = new Thickness(0, 2, 0, 2)
            };
            itemLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
                $"[font=\"Cozette\" size=14][color=#F8FAFC]{i + 1}. {escapedObjective}[/color][/font]"));
            ObjectivesListContainer.AddChild(itemLabel);
        }

        DeploySquadButton.Disabled = state.SquadDeployed;
        DeploySquadButton.Text = Loc.GetString(state.SquadDeployed ? DeployDoneLoc : DeployReadyLoc);

        LaunchFlightButton.Disabled = state.FlightPhase != STMarsocFlightPhase.DockedInDeepSpace;
        LaunchFlightButton.Text = state.FlightPhase switch
        {
            STMarsocFlightPhase.DockedInDeepSpace => Loc.GetString(LaunchReadyLoc),
            STMarsocFlightPhase.InTransit => Loc.GetString(LaunchTransitLoc, ("seconds", state.RemainingFlightSeconds)),
            _ => Loc.GetString(LaunchArrivedLoc)
        };

        CycleSectorButton.Disabled = state.SectorLocked;

        LockSectorButton.Disabled = false;
        LockSectorButton.Text = Loc.GetString(state.SectorLocked ? LockSectorDoneLoc : LockSectorReadyLoc);

        ToggleParadropButton.Disabled = state.FlightPhase != STMarsocFlightPhase.ArrivedInOrbit || !state.SectorLocked;
        ToggleParadropButton.Text = Loc.GetString(state.ParadropActive ? ParadropOnLoc : ParadropOffLoc);
    }

    private void StartSegment(int index)
    {
        if (_segments.Count == 0)
        {
            _currentSegmentIndex = 0;
            _visibleCharacters = 0;
            DialogueLabel.SetMessage(FormattedMessage.FromMarkupPermissive(string.Empty));
            SegmentCounterLabel.Text = string.Empty;
            return;
        }

        _currentSegmentIndex = Math.Clamp(index, 0, _segments.Count - 1);
        _visibleCharacters = 0;
        _typingAccumulator = 0f;
        _holdAccumulator = 0f;
        DialogueLabel.Modulate = Color.White;
        DialogueLabel.SetMessage(FormattedMessage.FromMarkupPermissive(string.Empty));

        SegmentCounterLabel.Text = Loc.GetString(
            SegmentCounterLoc,
            ("current", _currentSegmentIndex + 1),
            ("total", _segments.Count));
    }

    private void CompleteOrAdvanceSegment()
    {
        if (_segments.Count == 0)
            return;

        var activeText = _segments[_currentSegmentIndex];
        if (_visibleCharacters < activeText.Length)
        {
            _visibleCharacters = activeText.Length;
            _holdAccumulator = 0f;
            RenderCurrentSegmentText(activeText);
            return;
        }

        var nextIndex = (_currentSegmentIndex + 1) % _segments.Count;
        StartSegment(nextIndex);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_segments.Count == 0)
            return;

        var activeText = _segments[_currentSegmentIndex];
        var isSpeaking = _visibleCharacters < activeText.Length;
        if (_backdrop != null)
            _backdrop.IsSpeaking = isSpeaking;

        if (isSpeaking)
        {
            _typingAccumulator += args.DeltaSeconds;
            while (_typingAccumulator >= SecondsPerChar && _visibleCharacters < activeText.Length)
            {
                _typingAccumulator -= SecondsPerChar;
                _visibleCharacters++;
            }

            RenderCurrentSegmentText(activeText[.._visibleCharacters]);
            return;
        }

        _holdAccumulator += args.DeltaSeconds;
        if (_holdAccumulator >= SegmentHoldDuration)
        {
            var fadeElapsed = _holdAccumulator - SegmentHoldDuration;
            var alpha = Math.Clamp(1f - fadeElapsed / SegmentFadeDuration, 0f, 1f);
            DialogueLabel.Modulate = Color.White.WithAlpha(alpha);

            if (fadeElapsed >= SegmentFadeDuration)
            {
                var nextIndex = (_currentSegmentIndex + 1) % _segments.Count;
                StartSegment(nextIndex);
            }
        }
    }

    private void RenderCurrentSegmentText(string slice)
    {
        var escaped = FormattedMessage.EscapeText(slice);
        var markup = $"[font=\"Cozette\" size=15][color=#9AD1FF]{escaped}[/color][/font]";
        DialogueLabel.SetMessage(FormattedMessage.FromMarkupPermissive(markup));
    }

    private sealed class STMarsocCommandBackdrop : Control
    {
        private float _animTime;
        public bool IsSpeaking { get; set; }

        public STMarsocCommandBackdrop()
        {
            MouseFilter = MouseFilterMode.Ignore;
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            _animTime += args.DeltaSeconds;
        }

        protected override void Draw(DrawingHandleScreen handle)
        {
            base.Draw(handle);

            var w = (float)PixelWidth;
            var h = (float)PixelHeight;
            if (w <= 0f || h <= 0f)
                return;

            handle.DrawRect(new UIBox2(0f, 0f, w, h), Color.FromHex("#0B182E"));
            handle.DrawRect(new UIBox2(0f, h * 0.15f, w, h * 0.85f), Color.FromHex("#132647"));
            handle.DrawRect(new UIBox2(w * 0.18f, h * 0.08f, w * 0.82f, h * 0.92f), Color.FromHex("#241B2F"));
            handle.DrawRect(new UIBox2(w * 0.28f, h * 0.04f, w * 0.72f, h * 0.96f), Color.FromHex("#3D1E24"));

            var gridColor = new Color(56, 189, 248, 32);
            for (var x = 24f; x < w; x += 36f)
            {
                handle.DrawRect(new UIBox2(x, 0f, x + 1f, h), gridColor);
            }

            for (var y = 18f; y < h; y += 28f)
            {
                handle.DrawRect(new UIBox2(0f, y, w, y + 1f), gridColor);
            }

            var barColor = new Color(56, 189, 248, 135);
            var accentColor = new Color(245, 158, 11, 165);
            var centerY = h * 0.5f;

            for (var i = 0; i < 12; i++)
            {
                var wave = IsSpeaking
                    ? MathF.Abs(MathF.Sin(_animTime * 9f + i * 0.7f)) * 42f + 8f
                    : MathF.Abs(MathF.Sin(_animTime * 2f + i * 0.5f)) * 8f + 4f;

                var lx = 22f + i * 14f;
                handle.DrawRect(new UIBox2(lx, centerY - wave, lx + 8f, centerY + wave), i % 3 == 0 ? accentColor : barColor);

                var rx = w - 22f - i * 14f - 8f;
                handle.DrawRect(new UIBox2(rx, centerY - wave, rx + 8f, centerY + wave), i % 3 == 0 ? accentColor : barColor);
            }
        }
    }
